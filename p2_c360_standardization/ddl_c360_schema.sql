-- 1. BẢNG MAP ĐỊA BÀN HÀNH CHÍNH CẤP TỈNH (36 TỈNH MỚI 2025 & BIẾN THỂ MÃ CŨ)
CREATE TABLE IF NOT EXISTS C360_MAP_DBHC_TINH (
    MA_TINH_LOOKUP      VARCHAR2(10) NOT NULL,
    MA_TINH_MOI         VARCHAR2(3)  NOT NULL,
    TEN_TINH_MOI        VARCHAR2(200) NOT NULL,
    LOAI_MAP            VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_MAP_TINH PRIMARY KEY (MA_TINH_LOOKUP)
);

-- 2. BẢNG MAP ĐỊA BÀN HÀNH CHÍNH CẤP XÃ (3.322 XÃ MỚI 2025 & CÁC MÃ SÁP NHẬP)
CREATE TABLE IF NOT EXISTS C360_MAP_DBHC_XA (
    MA_XA_LOOKUP        VARCHAR2(10) NOT NULL,
    MA_XA_MOI           VARCHAR2(5),
    TEN_XA_MOI          VARCHAR2(200),
    MA_TINH_MOI         VARCHAR2(3),
    TEN_TINH_MOI        VARCHAR2(200),
    LOAI_MAP            VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_MAP_XA PRIMARY KEY (MA_XA_LOOKUP)
);

-- 3. BẢNG CHUẨN HÓA THÔNG TIN CÔNG DÂN (CUSTOMER 360)
CREATE TABLE IF NOT EXISTS C360_THONG_TIN_CA_NHAN (
    ID                  NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MA_SO_BHXH          VARCHAR2(30) NOT NULL,
    MA_SO_BHXH_CU       VARCHAR2(30),
    SO_DINH_DANH        VARCHAR2(12),
    HO_TEN              VARCHAR2(250) NOT NULL,
    HO_TEN_KHONG_DAU    VARCHAR2(250) NOT NULL,
    GIOI_TINH           NUMBER(1),
    NGAY_SINH_CHUAN     VARCHAR2(8),
    NGAY_SINH_GOC       VARCHAR2(30),
    SO_CCCD             VARCHAR2(50),
    SO_CMTND            VARCHAR2(50),
    SO_DIEN_THOAI       VARCHAR2(20),
    EMAIL               VARCHAR2(100),
    MA_TINH_THUONG_TRU  VARCHAR2(3),
    TEN_TINH_THUONG_TRU VARCHAR2(200),
    MA_XA_THUONG_TRU    VARCHAR2(5),
    TEN_XA_THUONG_TRU   VARCHAR2(200),
    DIA_CHI_THUONG_TRU  VARCHAR2(500),
    MA_TINH_LIEN_HE     VARCHAR2(3),
    MA_XA_LIEN_HE       VARCHAR2(5),
    DIA_CHI_LIEN_HE     VARCHAR2(500),
    MA_TINH_KHAI_SINH   VARCHAR2(3),
    MA_XA_KHAI_SINH     VARCHAR2(5),
    DIA_CHI_KHAI_SINH   VARCHAR2(500),
    DM_DAN_TOC_ID       NUMBER(19),
    MA_DAN_TOC          VARCHAR2(10),
    TEN_DAN_TOC         VARCHAR2(100),
    QUOC_TICH_RAW       VARCHAR2(50),
    MA_QUOC_TICH        VARCHAR2(10),
    TEN_QUOC_TICH       VARCHAR2(100),
    IS_ALIVE            NUMBER(1) DEFAULT 1,
    DEAD_DATE           VARCHAR2(30),
    SOURCE_MA_HO_GD     VARCHAR2(50),
    SOURCE_MODIFY_DATE  VARCHAR2(30),
    SOURCE_CREATED_DATE VARCHAR2(30),
    DQ_FLAGS            VARCHAR2(500),
    SYNC_DATE           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    SYNC_BATCH_ID       NUMBER(19),
    CONSTRAINT UK_C360_MA_BHXH UNIQUE (MA_SO_BHXH)
);

-- CHỈ MỤC TRÊN BẢNG C360 (TỐI ƯU TRA CỨU & API)
CREATE INDEX IF NOT EXISTS IDX_C360_MA_CU ON C360_THONG_TIN_CA_NHAN (MA_SO_BHXH_CU);
CREATE INDEX IF NOT EXISTS IDX_C360_SO_DINH_DANH ON C360_THONG_TIN_CA_NHAN (SO_DINH_DANH);
CREATE INDEX IF NOT EXISTS IDX_C360_TIM_KIEM ON C360_THONG_TIN_CA_NHAN (HO_TEN_KHONG_DAU, NGAY_SINH_CHUAN);
CREATE INDEX IF NOT EXISTS IDX_C360_THAY_DOI ON C360_THONG_TIN_CA_NHAN (SYNC_DATE, ID);
CREATE INDEX IF NOT EXISTS IDX_C360_TINH ON C360_THONG_TIN_CA_NHAN (MA_TINH_THUONG_TRU);

-- 4. BẢNG HÀNG ĐỢI ĐỒNG BỘ NEAR REAL-TIME (C360_SYNC_QUEUE)
CREATE TABLE IF NOT EXISTS C360_SYNC_QUEUE (
    QUEUE_ID            NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MA_CD               VARCHAR2(30) NOT NULL,
    ACTION              VARCHAR2(10) DEFAULT 'UPSERT',
    ENQUEUE_TIME        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS              VARCHAR2(20) DEFAULT 'PENDING'
);
CREATE INDEX IF NOT EXISTS IDX_QUEUE_MACD_STATUS ON C360_SYNC_QUEUE (STATUS, ENQUEUE_TIME);

-- 5. BẢNG ĐIỀU KHIỂN ĐỒNG BỘ & KHÓA TIẾN TRÌNH (C360_SYNC_CONTROL)
CREATE TABLE IF NOT EXISTS C360_SYNC_CONTROL (
    PROCESS_NAME        VARCHAR2(50) NOT NULL,
    PAUSE_NRT           NUMBER(1) DEFAULT 0,
    LAST_FULL_LOAD_TIME TIMESTAMP,
    LAST_NRT_RUN        TIMESTAMP,
    LAST_NRT_STATUS     VARCHAR2(50) DEFAULT 'READY',
    CONSTRAINT PK_SYNC_CONTROL PRIMARY KEY (PROCESS_NAME)
);

-- 6. BẢNG NHẬT KÝ ĐỒNG BỘ (C360_SYNC_LOG)
CREATE TABLE IF NOT EXISTS C360_SYNC_LOG (
    LOG_ID              NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BATCH_TYPE          VARCHAR2(20) NOT NULL,
    START_TIME          TIMESTAMP NOT NULL,
    END_TIME            TIMESTAMP,
    AFFECTED_KEYS       NUMBER(10) DEFAULT 0,
    MERGE_COUNT         NUMBER(10) DEFAULT 0,
    DELETE_COUNT        NUMBER(10) DEFAULT 0,
    STATUS              VARCHAR2(20) NOT NULL,
    ERROR_MSG           VARCHAR2(1000)
);

-- 7. BẢNG QUẢN LÝ TÀI KHOẢN API CLIENTS (BẢO MẬT X-API-KEY)
CREATE TABLE IF NOT EXISTS C360_API_CLIENTS (
    CLIENT_ID           VARCHAR2(50) PRIMARY KEY,
    API_KEY_HASH        VARCHAR2(64) NOT NULL,
    CLIENT_NAME         VARCHAR2(200) NOT NULL,
    SCOPES              VARCHAR2(200) NOT NULL,
    IS_ACTIVE           NUMBER(1) DEFAULT 1,
    CREATED_DATE        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. BẢNG NHẬT KÝ AUDIT TRA CỨU API (ASYNC BATCH AUDIT LOG)
CREATE TABLE IF NOT EXISTS C360_API_AUDIT_LOG (
    AUDIT_ID            NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CLIENT_ID           VARCHAR2(50),
    ENDPOINT            VARCHAR2(200) NOT NULL,
    METHOD              VARCHAR2(10) NOT NULL,
    QUERY_PARAM         VARCHAR2(1000),
    RESPONSE_STATUS     NUMBER(4) NOT NULL,
    EXEC_TIME_MS        NUMBER(10,2),
    MATCHED_BY          VARCHAR2(50),
    IP_ADDRESS          VARCHAR2(50),
    CREATED_TIME        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_CLIENT_DATE ON C360_API_AUDIT_LOG (CLIENT_ID, CREATED_TIME);
